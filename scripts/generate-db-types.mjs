/**
 * Regenerates src/types/database.types.ts from Supabase.
 * Requires the Supabase CLI (npx). Live is the default; use the local database
 * while developing an unapplied migration with `SUPABASE_LOCAL=true`.
 *
 *   npm run db:types
 *   SUPABASE_PROJECT_ID=... npm run db:types
 *   SUPABASE_LOCAL=true npm run db:types
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT_ID = process.env.SUPABASE_PROJECT_ID ?? 'lbqhiwudvifmkjtkccdg';
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outPath = path.join(repoRoot, 'src', 'types', 'database.types.ts');
const npxBin = process.platform === 'win32' ? 'npx.cmd' : 'npx';
const local = process.env.SUPABASE_LOCAL === 'true';
const sourceArgs = local ? ['--local'] : ['--project-id', PROJECT_ID];

const stdout = execFileSync(
  npxBin,
  ['--yes', 'supabase', 'gen', 'types', 'typescript', ...sourceArgs, '--schema', 'public'],
  { encoding: 'utf8', cwd: repoRoot, stdio: ['ignore', 'pipe', 'inherit'] },
);

const sourceLabel = local ? 'the local Supabase database' : 'the live Supabase project';
const header = `/**
 * Generated by \`npm run db:types\` from ${sourceLabel}.
 * Do not edit by hand. Diff this file after regeneration to detect schema drift.
 * See ADR-0020 / TASK-795.
 */

`;

const jsonStart = stdout.indexOf('export type Json');
const body = (jsonStart >= 0 ? stdout.slice(jsonStart) : stdout).replace(/\r\n/g, '\n');
writeFileSync(outPath, header + body, 'utf8');
console.log(`Wrote ${outPath} (${local ? 'local' : PROJECT_ID})`);
